use slot::baseos::{lookup, var_in};

const RELEASE: &str = "# Generated by build-rootfs.sh; do not edit in the image.
BASEOS=1
BASEOS_PLATFORM=h700
BASEOS_VERSION=1.3.0
BASEOS_TARGET=rg34xx
BASEOS_MODEL=\"Anbernic RG34XX\"
BASEOS_PANEL_ROTATION_CCW=0
";

#[test]
fn a_key_is_read_from_the_release_file() {
    assert_eq!(lookup(RELEASE, "BASEOS_TARGET").as_deref(), Some("rg34xx"));
    assert_eq!(
        lookup(RELEASE, "BASEOS_PANEL_ROTATION_CCW").as_deref(),
        Some("0")
    );
}

#[test]
fn a_quoted_value_loses_its_quotes() {
    assert_eq!(
        lookup(RELEASE, "BASEOS_MODEL").as_deref(),
        Some("Anbernic RG34XX")
    );
}

#[test]
fn a_key_is_not_matched_by_its_prefix() {
    assert_eq!(lookup(RELEASE, "BASEOS").as_deref(), Some("1"));
    assert_eq!(lookup(RELEASE, "BASEOS_TARG"), None);
}

#[test]
fn a_baseos_that_does_not_export_its_release_falls_back_to_the_file() {
    let dir = tempfile::tempdir().unwrap();
    let release = dir.path().join("baseos-release");
    std::fs::write(&release, RELEASE).unwrap();
    assert_eq!(
        var_in("BASEOS_TARGET", None, &release).as_deref(),
        Some("rg34xx")
    );
}

#[test]
fn the_environment_wins_over_the_file() {
    let dir = tempfile::tempdir().unwrap();
    let release = dir.path().join("baseos-release");
    std::fs::write(&release, RELEASE).unwrap();
    let env = Some("rg35xxsp".to_string());
    assert_eq!(
        var_in("BASEOS_TARGET", env, &release).as_deref(),
        Some("rg35xxsp")
    );
}

#[test]
fn no_file_and_no_environment_is_no_value() {
    let dir = tempfile::tempdir().unwrap();
    assert_eq!(
        var_in("BASEOS_TARGET", None, &dir.path().join("missing")),
        None
    );
}
